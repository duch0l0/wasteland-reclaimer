SKILL_BY_ID = {s["id"]: s for s in SKILLS}
STEP = 10          # сколько даёт одно повышение — пока навык слабый
CAP = 150


def step_for(value):
    """Чем выше навык, тем меньше даёт повышение (как «теги» в Fallout: дорого быть мастером во всём).
    до 60 — +10, 60–89 — +6, 90–119 — +4, от 120 — +2. Мастер в двух навыках к концу игры — да,
    во всех — нет: за игру ~12 повышений."""
    if value < 60:
        return STEP
    if value < 90:
        return 6
    if value < 120:
        return 4
    return 2
SPEECH_FOR_TONGUE = 60


def defaults(level=1):
    """Навыки нового героя. Для старых сохранений — примерно как росли раньше (+5 всем за уровень)."""
    grow = (level - 1) * 5
    return {s["id"]: s["base"] + (grow if s["id"] in ("guns", "melee") else 0) for s in SKILLS}


def choices(player):
    """Варианты для окна повышения уровня (то же окно, что у перков)."""
    out = []
    for s in SKILLS:
        v = player.skills.get(s["id"], s["base"])
        if v >= CAP:
            continue
        out.append({"kind": "skill", "id": s["id"], "max_rank": 1,
                    "name": f"{s['name']}: {v} → {min(CAP, v + step_for(v))}", "desc": s["desc"]})
    return out


def raise_skill(player, skill_id):
    v = player.skills.get(skill_id, SKILL_BY_ID[skill_id]["base"])
    player.skills[skill_id] = min(CAP, v + step_for(v))


def xp_for_kill(base_xp, enemy_level, player_level):
    """Опыт за убийство: за равного и сильного — полностью (за сильного — с надбавкой),
    за каждого уровня слабее — на четверть меньше, но не меньше пятой части."""
    diff = enemy_level - player_level
    if diff >= 0:
        return round(base_xp * (1 + 0.15 * min(diff, 6)))
    return max(1, round(base_xp * max(0.2, 1 - 0.25 * -diff)))
