"""
Навыки героя (в духе Fallout): с каждым уровнем — +10 к одному навыку на выбор,
перк — только на чётных уровнях. Опыта на уровень нужно всё больше (settings.XP_TO_LEVEL),
а за слабых врагов его почти не дают (xp_for_kill) — уровень зарабатывают квестами и
опасными боями, а не зачисткой крыс.

  guns      Стрельба      шанс попасть из огнестрела
  melee     Рукопашная    шанс попасть ломом и урон (+1 за каждые 10 сверх 60)
  medicine  Медицина      бинты, стимуляторы и аптечки лечат сильнее (+1% за очко сверх 15)
  science   Наука         взлом терминалов: +1 попытка за каждые 20 очков сверх 15
  speech    Красноречие   реплики [Красноречие]: от 60 — как у перка «Подвешенный язык»
  survival  Выживание     реже нападают в пустоши, опасную встречу можно заметить издалека и обойти;
                          раны вне боя заживают быстрее
"""

SKILLS = [
    {"id": "guns", "name": "Стрельба", "base": 50,
     "desc": "Шанс попасть из любого огнестрела: самопал, пистолет, винтовка, дробовик, автомат."},
    {"id": "melee", "name": "Рукопашная", "base": 60,
     "desc": "Шанс попасть ломом; каждые 10 очков сверх 60 — ещё +1 к урону."},
    {"id": "medicine", "name": "Медицина", "base": 15,
     "desc": "Лечебные предметы восстанавливают больше HP: +1% за каждое очко сверх 15."},
    {"id": "science", "name": "Наука", "base": 15,
     "desc": "Взлом терминалов: +1 попытка за каждые 20 очков сверх 15."},
    {"id": "speech", "name": "Красноречие", "base": 20,
     "desc": "С 60 открываются реплики [Красноречие] — уговорить, припугнуть, выторговать."},
    {"id": "survival", "name": "Выживание", "base": 20,
     "desc": "Реже нападают в пустоши; опасную встречу замечаешь издалека и обходишь. Раны заживают быстрее."},
]
SKILL_BY_ID = {s["id"]: s for s in SKILLS}
STEP = 10          # сколько даёт одно повышение
CAP = 150
SPEECH_FOR_TONGUE = 60


def defaults(level=1):
    """Навыки нового героя. Для старых сохранений — примерно как росли раньше (+5 всем за уровень)."""
    grow = (level - 1) * 5
    return {s["id"]: s["base"] + (grow if s["id"] in ("guns", "melee") else 0) for s in SKILLS}


def choices(player):
    """Варианты для окна повышения уровня (то же окно, что у перков)."""
    out = []
    for s in SKILLS:
        v = player.skills.get(s["id"], s["base"])
        if v >= CAP:
            continue
        out.append({"kind": "skill", "id": s["id"], "max_rank": 1,
                    "name": f"{s['name']}: {v} → {min(CAP, v + STEP)}", "desc": s["desc"]})
    return out


def raise_skill(player, skill_id):
    player.skills[skill_id] = min(CAP, player.skills.get(skill_id, SKILL_BY_ID[skill_id]["base"]) + STEP)


def xp_for_kill(base_xp, enemy_level, player_level):
    """Опыт за убийство: за равного и сильного — полностью (за сильного — с надбавкой),
    за каждого уровня слабее — на четверть меньше, но не меньше пятой части."""
    diff = enemy_level - player_level
    if diff >= 0:
        return round(base_xp * (1 + 0.15 * min(diff, 6)))
    return max(1, round(base_xp * max(0.2, 1 - 0.25 * -diff)))
